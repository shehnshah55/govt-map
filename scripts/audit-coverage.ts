/**
 * Coverage audit: honest numbers on how complete and how well sourced the data is.
 *
 *   npm run audit:coverage            writes docs/COVERAGE.md and the README "At a glance" block
 *   npm run audit:coverage -- --check fails if either file is out of date (used in CI)
 *
 * Output depends only on the data, never on the clock: record ages are measured from the
 * latest date that appears in the data (the "reference date"), so the report changes only
 * when the data changes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "./compile.ts";
import { GraphIndex, type Post } from "../src/lib/graph-index.ts";

const root = new URL("..", import.meta.url);
const COVERAGE = fileURLToPath(new URL("docs/COVERAGE.md", root));
const README = fileURLToPath(new URL("README.md", root));
const START = "<!-- coverage:start (generated by npm run audit:coverage; do not edit by hand) -->";
const END = "<!-- coverage:end -->";

// ── source levels (docs/LAUNCH_PLAN.md §0.2.2) ─────────────────────────────
export type SourceLevel = "1" | "2" | "3" | "reference" | "wikipedia" | "unclassified";
export const LEVEL_LABEL: Record<SourceLevel, string> = {
  "1": "1 · Official (law, gazette, government and official body sites)",
  "2": "2 · State media (APP, Radio Pakistan, PTV)",
  "3": "3 · Independent press",
  reference: "Reference works (not a source under §0.2)",
  wikipedia: "Wikipedia (not permitted as a source)",
  unclassified: "Unclassified",
};
const STATE_MEDIA = new Set(["radio.gov.pk", "app.com.pk", "ptv.com.pk", "ptvnews.com.pk"]);
const OFFICIAL_NON_GOV = new Set(["sbp.org.pk", "nepra.org.pk", "ogra.org.pk", "pmdc.pk"]);
const PRESS = new Set([
  "dawn.com", "tribune.com.pk", "thenews.com.pk", "thenews.pk", "brecorder.com", "geo.tv", "aaj.tv", "english.aaj.tv",
  "nation.com.pk", "arabnews.com", "arabnews.pk", "propakistani.pk", "24newshd.tv", "thenationalnews.com", "pakobserver.net",
  "aljazeera.com", "pakistantoday.com.pk", "dunyanews.tv", "arynews.tv", "samaa.tv", "dailytimes.com.pk", "thefridaytimes.com",
  "reuters.com", "bbc.com", "bbc.co.uk", "urdupoint.com",
]);
const REFERENCE = new Set(["britannica.com"]);

export function sourceLevel(host: string): SourceLevel {
  const h = host.replace(/^www\./, "");
  if (h.endsWith("wikipedia.org")) return "wikipedia";
  if (STATE_MEDIA.has(h)) return "2";
  if (h.endsWith(".gov.pk") || h === "gov.pk" || OFFICIAL_NON_GOV.has(h)) return "1";
  if (PRESS.has(h)) return "3";
  if (REFERENCE.has(h)) return "reference";
  return "unclassified";
}

// ── helpers ────────────────────────────────────────────────────────────────
const pct = (n: number, d: number) => (d === 0 ? "–" : n > 0 && n / d < 0.01 ? "<1%" : `${Math.round((100 * n) / d)}%`);
const frac = (n: number, d: number) => `${n.toLocaleString("en-US")} / ${d.toLocaleString("en-US")} (${pct(n, d)})`;
const num = (n: number) => n.toLocaleString("en-US");
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(" | ")} |`, `|${head.map((_, i) => (i === 0 ? "---" : "---:")).join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const toDate = (s: string) => new Date(`${s.length === 4 ? `${s}-01-01` : s.length === 7 ? `${s}-01` : s.slice(0, 10)}T00:00:00Z`);
const days = (from: string, to: string) => Math.floor((toDate(to).getTime() - toDate(from).getTime()) / 86_400_000);

export function audit(dataDir = fileURLToPath(new URL("data", root))) {
  const { graph: g, errors } = compile(dataDir);
  if (errors.length) throw new Error(`data does not compile:\n${errors.join("\n")}`);
  const ix = new GraphIndex(g);

  // Reference date: the latest date recorded anywhere in the data.
  const dates: string[] = [];
  for (const p of g.people) dates.push(p.as_of);
  for (const v of g.verification) if (v.checked) dates.push(v.checked);
  const walk = (x: unknown): void => {
    if (Array.isArray(x)) return x.forEach(walk);
    if (x && typeof x === "object") {
      const o = x as Record<string, unknown>;
      if (typeof o.accessed === "string") dates.push(o.accessed);
      Object.values(o).forEach(walk);
    }
  };
  walk(g);
  const refDate = dates.filter((d) => /^\d{4}(-\d{2}){0,2}$/.test(d)).sort().at(-1)!;

  // ── organisations ──
  const orgsAuth = g.organizations.filter((o) => !o.generated);
  const orgsGen = g.organizations.filter((o) => o.generated);
  const orgFields: [string, (o: (typeof g.organizations)[number]) => boolean][] = [
    ["legal_basis", (o) => !!o.legal_basis?.length],
    ["sources", (o) => !!o.sources?.length],
    ["website", (o) => !!o.website],
    ["description", (o) => !!o.description],
    ["established", (o) => !!o.established],
    ["name_ur", (o) => !!o.name_ur],
    ["budget", (o) => !!o.budget?.length],
    ["employees", (o) => !!o.employees],
  ];

  // ── posts ──
  const postsAuth = g.positions.filter((p) => !p.generated);
  const postsGen = g.positions.filter((p) => p.generated);
  const live = (p: Post) => !ix.org.get(p.org)?.abolished;
  const single = g.positions.filter((p) => live(p) && !((p.seats ?? 1) > 1));
  const held = (p: Post) => ix.effectiveHolders(p.id).length > 0;
  const govOf = (p: Post) => {
    const o = ix.org.get(p.org);
    const tier = o ? ix.tierOf(o.jurisdiction) : undefined;
    return tier ? (tier.id === "pk" ? "Federal" : tier.name) : "Unknown";
  };
  const KINDS: [string, (p: Post) => boolean][] = [
    ["Legislative seats (single-member)", (p) => p.id.startsWith("seat-")],
    ["Party offices", (p) => ix.org.get(p.org)?.kind === "political_party"],
    ["Heads of state and government", (p) => /(^fed-president|prime-minister|chief-minister|-governor)$/.test(p.id)],
    ["Deputy Commissioners", (p) => /-deputy-commissioner$/.test(p.id)],
    ["Commissioners", (p) => /-commissioner$/.test(p.id) && ix.org.get(p.org)?.kind === "field_administration"],
    ["Chief Secretaries", (p) => /-chief-secretary$/.test(p.id)],
    ["Inspectors General of Police", (p) => /-igp$/.test(p.id)],
    ["Ministers and advisers", (p) => /-minister$|-adviser$/.test(p.id)],
    ["Secretaries", (p) => /-secretary$/.test(p.id)],
    ["Judges and chief justices", (p) => p.role === "chief_justice" || p.role === "judge"],
    ["Heads of regulators", (p) => ix.org.get(p.org)?.kind === "regulator" && ["head", "chief"].includes(p.role)],
  ];
  const kindOf = (p: Post) => KINDS.find(([, f]) => f(p))?.[0] ?? "Other posts";
  const group = (key: (p: Post) => string) => {
    const m = new Map<string, { n: number; h: number }>();
    for (const p of single) {
      const k = key(p);
      const e = m.get(k) ?? { n: 0, h: 0 };
      e.n++;
      if (held(p)) e.h++;
      m.set(k, e);
    }
    return m;
  };
  const byGov = group(govOf);
  const byKind = group(kindOf);
  const singleHeld = single.filter(held).length;
  const vacantMarked = single.filter((p) => p.vacant).length;

  // Legislative seats. Each house has a seat roster (seat-* posts, with grouped reserved seats)
  // and may also have an umbrella post such as "Member of the National Assembly" (seats: 336).
  // Seats are counted from the roster; a member counts as named if they hold any member post of the house.
  const houses = new Map<string, Post[]>();
  for (const p of g.positions)
    if (p.role === "member" && live(p) && ["chamber", "legislature"].includes(ix.org.get(p.org)?.kind ?? ""))
      houses.set(p.org, [...(houses.get(p.org) ?? []), p]);
  let seatTotal = 0;
  let seatNamed = 0;
  for (const posts of houses.values()) {
    const roster = posts.filter((p) => p.id.startsWith("seat-"));
    const seats = (roster.length ? roster : posts).reduce((s, p) => s + (p.seats ?? 1), 0);
    const members = new Set(posts.flatMap((p) => ix.currentHolders(p.id).map((h) => h.person.id)));
    seatTotal += seats;
    seatNamed += Math.min(members.size, seats);
  }

  // ── people ──
  const currentRoles = g.people.flatMap((p) => p.roles.filter((r) => !r.until).map((r) => ({ p, r })));
  const rolesSourced = currentRoles.filter(({ r }) => r.source?.url).length;
  const withCurrent = g.people.filter((p) => p.roles.some((r) => !r.until));
  const allSourced = withCurrent.filter((p) => p.roles.filter((r) => !r.until).every((r) => r.source?.url)).length;
  const age = { fresh: 0, mid: 0, stale: 0 };
  for (const p of g.people) {
    const d = days(p.as_of, refDate);
    if (d < 90) age.fresh++;
    else if (d <= 180) age.mid++;
    else age.stale++;
  }
  const conf = { high: 0, medium: 0, low: 0 } as Record<string, number>;
  for (const p of g.people) conf[p.confidence ?? "high"]++;
  const asOfs = g.people.map((p) => p.as_of).sort();

  // ── laws ──
  const lawsUrl = g.laws.filter((l) => l.url).length;
  const lawsSummary = g.laws.filter((l) => l.summary).length;
  const lawYears = g.laws.map((l) => l.year).filter((y): y is number => typeof y === "number").sort((a, b) => a - b);

  // ── sources (authored records only; generated records copy their block's sources) ──
  const cites: string[] = [];
  let accessed = 0;
  const collect = (x: unknown): void => {
    if (Array.isArray(x)) return x.forEach(collect);
    if (x && typeof x === "object") {
      const o = x as Record<string, unknown>;
      if (typeof o.title === "string" && typeof o.url === "string") {
        cites.push(o.url);
        if (typeof o.accessed === "string") accessed++;
      }
      Object.values(o).forEach(collect);
    }
  };
  collect(orgsAuth);
  collect(postsAuth);
  collect(g.people);
  collect(g.verification);
  const byDomain = new Map<string, number>();
  const byLevel = new Map<SourceLevel, number>();
  let badUrls = 0;
  for (const u of cites) {
    let host: string;
    try {
      host = new URL(u).hostname.replace(/^www\./, "");
    } catch {
      badUrls++;
      continue;
    }
    byDomain.set(host, (byDomain.get(host) ?? 0) + 1);
    const lv = sourceLevel(host);
    byLevel.set(lv, (byLevel.get(lv) ?? 0) + 1);
  }
  const uniqueUrls = new Set(cites).size;
  const jurCount = (k: string) => g.jurisdictions.filter((j) => j.kind === k).length;

  // ── COVERAGE.md ──
  const md = `# Data coverage

Generated by \`npm run audit:coverage\` from the data in \`data/\`. Do not edit by hand: CI fails if this file is out of date.

**Reference date: ${refDate}** (the latest date recorded in the data). Record ages below are measured from this date, not from today.

## Organisations

${num(g.organizations.length)} in total: **${num(orgsAuth.length)} authored** in \`data/\` and ${num(orgsGen.length)} generated by the build (division and district offices). Field completeness is measured on authored organisations.

${table(["Field", "Authored organisations with it"], orgFields.map(([f, test]) => [`\`${f}\``, frac(orgsAuth.filter(test).length, orgsAuth.length)]))}

## Posts

${num(g.positions.length)} in total: **${num(postsAuth.length)} authored** and ${num(postsGen.length)} generated by naming conventions (ministers, secretaries, Commissioners, DCs, heads of bodies and every legislative seat; see \`docs/DATA_MODEL.md\`).

**Single-seat posts with a known current holder: ${frac(singleHeld, single.length)}.** Grouped posts (reserved seats, "Senator", "Member") and posts of abolished bodies are excluded. A holder counts if a person record holds the post now, directly or ex officio. ${num(vacantMarked)} posts are marked vacant and count as having no holder.

### By government

${table(["Government", "Single-seat posts with a current holder"], [...byGov].sort((a, b) => b[1].n - a[1].n).map(([k, v]) => [k, frac(v.h, v.n)]))}

### By kind

${table(["Kind of post", "Single-seat posts with a current holder"], [...byKind].sort((a, b) => b[1].n - a[1].n).map(([k, v]) => [k, frac(v.h, v.n)]))}

### Legislative seats

${table(["", "Count"], [
    ["Seats in every chamber (general and reserved)", num(seatTotal)],
    ["Seats with a named current member", frac(seatNamed, seatTotal)],
  ])}

## People

${table(["", "Count"], [
    ["People", num(g.people.length)],
    ["People holding at least one current post", num(withCurrent.length)],
    ["Current roles with a source", frac(rolesSourced, currentRoles.length)],
    ["People whose every current role has a source", frac(allSourced, withCurrent.length)],
    ["People with an Urdu name (`name_ur`)", frac(g.people.filter((p) => p.name_ur).length, g.people.length)],
  ])}

### Age of the \`as_of\` date (at the reference date)

${table(["Age", "People"], [
    ["Under 90 days", frac(age.fresh, g.people.length)],
    ["90 to 180 days", frac(age.mid, g.people.length)],
    ["Over 180 days", frac(age.stale, g.people.length)],
  ])}

\`as_of\` dates range from ${asOfs[0]} to ${asOfs.at(-1)}.

### Confidence

${table(["Confidence", "People"], (["high", "medium", "low"] as const).map((c) => [c, frac(conf[c] ?? 0, g.people.length)]))}

## Laws

${table(["", "Count"], [
    ["Laws", num(g.laws.length)],
    ["With a URL to the text", frac(lawsUrl, g.laws.length)],
    ["With a summary", frac(lawsSummary, g.laws.length)],
  ])}

Laws cited range from ${lawYears[0]} to ${lawYears.at(-1)}.

## Sources

${num(cites.length)} source citations on authored records, people and the verification log (${num(uniqueUrls)} distinct URLs${badUrls ? `, ${badUrls} unparseable` : ""}). Law text URLs are counted under Laws. Levels follow \`docs/LAUNCH_PLAN.md\` §0.2.

Citations with an \`accessed\` date (required by §0.2.4): ${frac(accessed, cites.length)}.

### By level

${table(["Level", "Citations"], (Object.keys(LEVEL_LABEL) as SourceLevel[]).map((lv) => [LEVEL_LABEL[lv], frac(byLevel.get(lv) ?? 0, cites.length)]))}

### By domain

${table(["Domain", "Level", "Citations"], [...byDomain].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([d, n]) => [d, sourceLevel(d), num(n)]))}
`;

  // ── README "At a glance" block ──
  const regulators = orgsAuth.filter((o) => o.kind === "regulator").length;
  const parties = orgsAuth.filter((o) => o.kind === "political_party").length;
  const glance = `${START}
| | |
|---|---|
| Government bodies | ${num(g.organizations.length)}: ${num(orgsAuth.length)} authored (including ${num(regulators)} regulators and ${num(parties)} political parties) and ${num(orgsGen.length)} division and district offices generated by the build |
| Posts | ${num(g.positions.length)}: ${num(postsAuth.length)} authored and ${num(postsGen.length)} generated by naming conventions, including every legislative seat. Each has its appointment method, appointing authority and legal basis |
| Posts with a known current holder | ${frac(singleHeld, single.length)} of single-seat posts |
| Legislative seats with a named member | ${frac(seatNamed, seatTotal)} |
| Jurisdictions | ${num(jurCount("province"))} provinces, ICT, GB, AJK, ${num(jurCount("division"))} divisions, ${num(jurCount("district"))} districts, ${num(jurCount("constituency"))} constituencies |
| People | ${num(g.people.length)}; ${frac(rolesSourced, currentRoles.length)} of current roles cite a source |
| Laws | ${num(g.laws.length)}; ${num(lawsUrl)} link to their text, ${num(lawsSummary)} have a summary |
| Connections | ${num(g.edges.length)} typed edges |
| Data date range | Laws from ${lawYears[0]} to ${lawYears.at(-1)}; officeholder records last checked between ${asOfs[0]} and ${asOfs.at(-1)} |

Full breakdown: [docs/COVERAGE.md](docs/COVERAGE.md).
${END}`;

  return { md, glance };
}

function spliceReadme(readme: string, glance: string) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`README.md needs the markers ${START} … ${END}`);
  return readme.slice(0, a) + glance + readme.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { md, glance } = audit();
  const readme = spliceReadme(readFileSync(README, "utf8"), glance);
  if (process.argv.includes("--check")) {
    const stale: string[] = [];
    if (readFileSync(COVERAGE, "utf8") !== md) stale.push("docs/COVERAGE.md");
    if (readFileSync(README, "utf8") !== readme) stale.push("README.md");
    if (stale.length) {
      console.error(`Out of date: ${stale.join(", ")}. Run \`npm run audit:coverage\` and commit the result.`);
      process.exit(1);
    }
    console.log("coverage: docs/COVERAGE.md and README.md are up to date");
  } else {
    writeFileSync(COVERAGE, md);
    writeFileSync(README, readme);
    console.log("coverage: wrote docs/COVERAGE.md and the README At a glance block");
  }
}
